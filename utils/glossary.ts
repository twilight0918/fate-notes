// ─── Palace name normalization ────────────────────────────────────
// iztro 回傳的宮位名稱不一定帶「宮」，且用「僕役」不是「交友」。
// glossary keys 統一使用帶「宮」版本，這裡做轉換。

const PALACE_NAME_MAP: Record<string, string> = {
  "僕役": "交友宮",
  "命宮": "命宮",
};

/** 將 iztro 的宮位名稱轉為 glossary key 格式（帶「宮」） */
export function normalizePalaceName(iztroName: string): string {
  if (PALACE_NAME_MAP[iztroName]) return PALACE_NAME_MAP[iztroName];
  if (iztroName.endsWith("宮")) return iztroName;
  return iztroName + "宮";
}

