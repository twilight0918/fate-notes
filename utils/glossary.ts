/** 取得欄位定義 */
export function getFieldDesc(key: string): string | undefined {
  return GLOSSARY[key]?.label;
}

/** 取得值說明 */
export function getValueDesc(key: string): string | undefined {
  return GLOSSARY[key]?.content;
}

/** 取得 Tooltip props（fieldDesc + valueDesc） */
export function getTooltipProps(
  fieldKey: string,
  valueKey?: string,
): { fieldDesc?: string; valueDesc?: string } {
  return {
    fieldDesc: getFieldDesc(fieldKey),
    valueDesc: valueKey ? getValueDesc(valueKey) : undefined,
  };
}
